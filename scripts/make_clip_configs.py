"""Generate configs that fit ONLY a held-out session's neuron params, from n distinct clips.

Start from a model trained on `scaling_laws_8` (e.g. omnimouse_5M for 1M steps); it has ZERO
overlap with the sensorium_2023 sessions, so 29712-5-9 is genuinely unseen -- its `sess_params`
do not exist in the checkpoint and are created fresh. The session is also absent from
`scaling_laws_pretraining`, which matters: a session listed there has its `valid_condition`
replaced, which would silently undo the clip filter below. `finetuning=true` then freezes `core_parameters()` and
trains only `_session_embedding`, `_neuron_embeddings`, `_neuron_biases`.

The sweep variable is the number of DISTINCT CLIPS the fit may see, expressed as an explicit
list of `condition_hash` values in `valid_condition` (a sum-of-products: entries OR'd). This is
Clips are drawn with a fixed seed so every n is a superset of the previous one -- the curve then
measures added clips, not a different random subset each time.

    python scripts/make_clip_configs.py      # writes configs/experiment/r3_clips{2..256}.yaml
    uv run train experiment=r3_clips32 ckpt_path=<scaling_laws_8 checkpoint>
"""
import glob
import json
import os
import random
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Same default as paths.data_dir in configs/paths/default.yaml.
DATA = os.environ.get("OMNIMOUSE_DATA_DIR", os.path.join(REPO, "data"))
OUT = os.environ.get("R3_OUT", os.path.join(REPO, "configs", "experiment"))
SESSION = os.environ.get("R3_SESSION", "29712-5-9")
COUNTS = [int(x) for x in os.environ.get("R3_COUNTS", "2,4,8,16,32,64,128,256").split(",")]
SEED = 0

d = glob.glob(f"{DATA}/dynamic{SESSION}-*")[0]
meta = json.load(open(f"{d}/screen/combined_meta.json"))

# distinct clips available in this session's train tier
hashes = sorted({v["condition_hash"] for v in meta.values()
                 if v.get("tier") == "train" and v.get("stim_type") == "stimulus.Clip"
                 and v.get("condition_hash")})
random.Random(SEED).shuffle(hashes)
print(f"session {SESSION}: {len(hashes)} distinct train clips available")

session_dir = os.path.basename(d)

for n in COUNTS:
    if n > len(hashes):
        print(f"  skip n={n} (only {len(hashes)} clips available)")
        continue
    chosen = hashes[:n]                      # nested: n=4 contains n=2
    conds = "\n".join(
        f"          - tier: train\n"
        f"            stim_type: stimulus.Clip\n"
        f"            condition_hash: {h}" for h in chosen
    )
    body = f"""# @package _global_
#
# AUTO-GENERATED by make_clip_cfg.py -- do not edit by hand.
# Result 3: fit ONLY the held-out session's neuron embeddings + biases, from {n} distinct clips.
# Session {SESSION} is absent from scaling_laws_8, so the checkpoint has genuinely never seen it.

defaults:
  - /model/masking_strategies: training
  - _self_

paths:
  run_name: r3_{SESSION.replace('-', '_')}_clips{n}
  experiment_name: omnimouse-neuron-fit

# Freezes core_parameters(); leaves only sess_params trainable. Also sets
# strict=False / load_weights_only=True so a checkpoint without this session loads.
finetuning: true

data:
  # the held-out session only
  dataset_collection: ["{session_dir}"]
  pretraining_datasets: "scaling_laws_pretraining"
  validation_datasets: null
  test_datasets: null
  expose_extra_meta_conditions: true

  train_dataset:
    modality_config:
      screen:
        sample_stride: 1
        valid_condition:
{conds}

  validation_dataset:
    modality_config:
      screen:
        sample_stride: 60
        include_blanks: true
        # Held-out clips, identical for every n -- the curve must move because the FIT
        # improves, not because the evaluation set changed.
        valid_condition:
          - tier: validation
            stim_type: stimulus.Clip

  dataloader:
    batch_size: 8

model:
  num_self_attends_per_block: 6
  d_model: 256
  num_heads: 4
  hiera_stages: [2, 2]
  local_to_global_ratio: [5, 1]

trainer:
  # Measured 2.39 s/step on 1xA100 (the backward still traverses the frozen core to reach
  # the neuron embeddings, so freezing saves little compute). 5000 steps ~= 3.3 h, inside a
  # 4 h wall, and gives 10 validation points.
  max_steps: 5000
  max_epochs: 100
  val_every_n_steps: 500
  # sess_params are the ONLY trainable tensors here; rank_lr is their LR.
  rank_lr: 3e-3
"""
    p = f"{OUT}/r3_clips{n}.yaml"
    open(p, "w").write(body)
    print(f"  wrote {os.path.basename(p)}  ({n} clips)")
